import type { PagesFunction } from '@cloudflare/workers-types';
import { type Env, requirePermission, jsonOk, jsonError, serverError } from '../../lib/session';
import { sendEmail, calendarEventEmail } from '../../lib/email';

function serializeEvent(r: Record<string, unknown>, propertyIds?: string[]) {
  return {
    id: r.id,
    propertyId: r.property_id ?? undefined,
    propertyIds: propertyIds ?? (r.property_id ? [r.property_id as string] : []),
    unitId: r.unit_id ?? undefined,
    title: r.title,
    description: r.description ?? undefined,
    category: r.category,
    eventDate: r.event_date,
    endDate: r.end_date ?? undefined,
    eventTime: r.event_time ?? undefined,
    endTime: r.end_time ?? undefined,
    priority: r.priority ?? 'medium',
    isRecurring: !!r.is_recurring,
    recurrenceRule: r.recurrence_rule ?? undefined,
    completed: !!r.completed,
    completedAt: r.completed_at ?? undefined,
    notes: r.notes ?? undefined,
    reminderHours: r.reminder_hours != null ? Number(r.reminder_hours) : undefined,
    createdAt: r.created_at,
    isAuto: !!r.is_auto,
  };
}

async function getPropertyIdsForEvents(env: Env, eventIds: string[]): Promise<Map<string, string[]>> {
  if (eventIds.length === 0) return new Map();
  const { results } = await env.DB.prepare(
    `SELECT event_id, property_id FROM calendar_event_properties WHERE event_id IN (${eventIds.map(() => '?').join(',')})`,
  ).bind(...eventIds).all();
  const map = new Map<string, string[]>();
  for (const r of (results || [])) {
    const eid = r.event_id as string;
    if (!map.has(eid)) map.set(eid, []);
    map.get(eid)!.push(r.property_id as string);
  }
  return map;
}

async function syncEventProperties(env: Env, eventId: string, propertyIds: string[]) {
  await env.DB.prepare('DELETE FROM calendar_event_properties WHERE event_id = ?').bind(eventId).run();
  if (propertyIds.length > 0) {
    const values = propertyIds.map(() => '(?, ?)').join(', ');
    const binds: string[] = [];
    for (const pid of propertyIds) { binds.push(eventId, pid); }
    await env.DB.prepare(
      `INSERT OR IGNORE INTO calendar_event_properties (event_id, property_id) VALUES ${values}`
    ).bind(...binds).run();
  }
}

async function notifyAdmins(env: Env, type: 'created' | 'updated' | 'cancelled', eventRow: Record<string, unknown>, propertyIds?: string[]) {
  const admins = await env.DB.prepare(
    `SELECT email FROM user WHERE role IN ('super_admin', 'admin') AND email IS NOT NULL`
  ).all();
  const emails = (admins.results || []).map(r => r.email as string).filter(Boolean);
  if (emails.length === 0) return;

  let propertyName: string | undefined;
  const pids = propertyIds ?? (eventRow.property_id ? [eventRow.property_id as string] : []);
  if (pids.length > 0) {
    const placeholders = pids.map(() => '?').join(',');
    const { results } = await env.DB.prepare(
      `SELECT name, address FROM properties WHERE id IN (${placeholders})`
    ).bind(...pids).all();
    propertyName = (results || []).map(r => (r.name || r.address) as string).filter(Boolean).join(', ');
  }

  const unitRow = eventRow.unit_id
    ? ((await env.DB.prepare('SELECT unit_number FROM units WHERE id = ?').bind(eventRow.unit_id).first()) as { unit_number?: string } | null)
    : null;

  const email = calendarEventEmail({
    type,
    title: eventRow.title as string,
    eventDate: eventRow.event_date as string,
    propertyName: propertyName || undefined,
    unitLabel: unitRow?.unit_number ? `Unit ${unitRow.unit_number}` : undefined,
    description: (eventRow.description as string) || undefined,
    category: (eventRow.category as string) || undefined,
    priority: (eventRow.priority as string) || undefined,
  });

  for (const to of emails) {
    await sendEmail(env, { to, ...email });
  }
}

/** Generate synthetic calendar events from lease milestones and user birthdays. */
async function autoGeneratedEvents(env: Env): Promise<Record<string, unknown>[]> {
  const auto: Record<string, unknown>[] = [];

  // 1. Lease milestones: expiration, renewal start_date, termination (ended status),
  //    and move-in (lease start_date).
  try {
    const { results: leases } = await env.DB.prepare(
      `SELECT l.id, l.start_date, l.end_date, l.status, l.end_reason,
              l.property_id, l.unit_id,
              p.name AS prop_name, p.address AS prop_addr,
              u.unit_number,
              GROUP_CONCAT(t.first_name || ' ' || t.last_name, ', ') AS tenant_names
         FROM leases l
         LEFT JOIN properties p ON p.id = l.property_id
         LEFT JOIN units u ON u.id = l.unit_id
         LEFT JOIN lease_tenants lt ON lt.lease_id = l.id
         LEFT JOIN tenants t ON t.id = lt.tenant_id
        GROUP BY l.id`
    ).all();
    const propLabel = (r: Record<string, unknown>) => {
      const parts: string[] = [];
      if (r.prop_name || r.prop_addr) parts.push((r.prop_name || r.prop_addr) as string);
      if (r.unit_number) parts.push(`Unit ${r.unit_number}`);
      return parts.join(', ');
    };

    for (const l of (leases || []) as Record<string, unknown>[]) {
      const loc = propLabel(l);
      const who = (l.tenant_names as string) || 'Unknown';

      // Move-in date
      if (l.start_date) {
        auto.push({
          id: `auto-movein-${l.id}`, property_id: l.property_id, unit_id: l.unit_id,
          title: `Move In: ${who}`, description: loc,
          category: 'move_in', event_date: l.start_date, priority: 'medium',
          is_recurring: 0, completed: 0, is_auto: 1,
        });
      }

      // Lease expiration
      if (l.end_date && l.status !== 'ended') {
        auto.push({
          id: `auto-expiry-${l.id}`, property_id: l.property_id, unit_id: l.unit_id,
          title: `Lease Expires: ${who}`, description: loc,
          category: 'lease_expiration', event_date: l.end_date, priority: 'high',
          is_recurring: 0, completed: 0, is_auto: 1,
        });
      }

      // Lease termination (ended leases with an end_date)
      if (l.status === 'ended' && l.end_date) {
        auto.push({
          id: `auto-term-${l.id}`, property_id: l.property_id, unit_id: l.unit_id,
          title: `Lease Terminated: ${who}`,
          description: l.end_reason ? `${loc} (${l.end_reason})` : loc,
          category: 'lease_termination', event_date: l.end_date, priority: 'medium',
          is_recurring: 0, completed: 1, is_auto: 1,
        });
      }
    }
  } catch { /* pre-migration safe */ }

  // 2. Team member birthdays (annually recurring, shown in current year).
  try {
    const { results: users } = await env.DB.prepare(
      `SELECT u.id, u.name, u.birthdate
         FROM user u
         JOIN user_roles r ON r.user_id = u.id
        WHERE u.birthdate IS NOT NULL AND u.is_active = 1
          AND r.role NOT IN ('tenant', 'realtor', 'handyman')`
    ).all();
    for (const u of (users || []) as Record<string, unknown>[]) {
      const bd = u.birthdate as string; // YYYY-MM-DD
      const monthDay = bd.substring(5);  // MM-DD
      const name = (u.name as string) || 'Team Member';
      auto.push({
        id: `auto-bday-${u.id}`, title: `🎂 ${name}'s Birthday`,
        category: 'birthday', event_date: bd,
        priority: 'low', is_recurring: 1, recurrence_rule: 'annually',
        completed: 0, is_auto: 1, description: monthDay,
      });
    }
  } catch { /* pre-migration safe */ }

  return auto;
}

export const onRequestGet: PagesFunction<Env> = async (context) => {
  const { env, request } = context;
  const auth = await requirePermission(env, request, 'finances_view');
  if (auth instanceof Response) return auth;

  try {
    const { results } = await env.DB.prepare(
      'SELECT * FROM calendar_events ORDER BY event_date ASC'
    ).all();
    const rows = (results || []) as Record<string, unknown>[];
    const eventIds = rows.map(r => r.id as string);
    const propMap = await getPropertyIdsForEvents(env, eventIds);

    const manual = rows.map(r => serializeEvent(r, propMap.get(r.id as string) || []));
    const auto = (await autoGeneratedEvents(env)).map(r => serializeEvent(r));
    return jsonOk({ success: true, data: [...manual, ...auto] });
  } catch {
    return serverError();
  }
};

export const onRequestPost: PagesFunction<Env> = async (context) => {
  const { env, request } = context;
  const auth = await requirePermission(env, request, 'finances_expenses');
  if (auth instanceof Response) return auth;

  try {
    const body = (await request.json()) as Record<string, unknown>;
    if (!body.title || !body.category || !body.eventDate) {
      return jsonError('Title, category, and event date are required', 400);
    }

    const propertyIds = Array.isArray(body.propertyIds) ? (body.propertyIds as string[]).filter(Boolean) : [];
    const primaryPropertyId = propertyIds[0] ?? (body.propertyId as string) ?? null;

    const id = crypto.randomUUID();
    await env.DB.prepare(
      `INSERT INTO calendar_events (id, property_id, unit_id, title, description, category, event_date, end_date, event_time, end_time, priority, is_recurring, recurrence_rule, notes, user_id, reminder_hours)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`
    ).bind(
      id,
      primaryPropertyId,
      body.unitId ?? null,
      body.title,
      body.description ?? null,
      body.category,
      body.eventDate,
      body.endDate ?? null,
      body.eventTime ?? null,
      body.endTime ?? null,
      body.priority ?? 'medium',
      body.isRecurring ? 1 : 0,
      body.recurrenceRule ?? null,
      body.notes ?? null,
      auth.id,
      body.reminderHours ?? null,
    ).run();

    if (propertyIds.length > 0) {
      await syncEventProperties(env, id, propertyIds);
    } else if (primaryPropertyId) {
      await syncEventProperties(env, id, [primaryPropertyId]);
    }

    const row = await env.DB.prepare('SELECT * FROM calendar_events WHERE id = ?').bind(id).first();
    const pids = propertyIds.length > 0 ? propertyIds : (primaryPropertyId ? [primaryPropertyId] : []);
    context.waitUntil(notifyAdmins(env, 'created', row as Record<string, unknown>, pids));
    return jsonOk({ success: true, data: serializeEvent(row as Record<string, unknown>, pids) }, 201);
  } catch {
    return serverError();
  }
};
